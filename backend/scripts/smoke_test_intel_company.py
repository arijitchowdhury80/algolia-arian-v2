"""Smoke test for intel-company v2 — 3-track pipeline with full pipeline health tracking.

Tests the full call path:
  Track 1: WebFetch (leadership, IR, newsroom pages via shared browser infra)
  Track 2: Perplexity sonar-pro (web research)
  Track 3: Synthesis LLM (Gemini reconciliation)

Every failure, fallback, and degradation is captured in PipelineHealthLog
and surfaced in both the markdown report and JSON output.

Usage:
    python3 scripts/smoke_test_intel_company.py nike.com
    python3 scripts/smoke_test_intel_company.py orientaltrading.com
"""

